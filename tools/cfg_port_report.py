"""Per-group report on the configuration port: ported / verdict / 2027 firings,
or blocked and on which named input.

Reads the registry and fires it over build/astronomy_2027.json. Computes
nothing of its own: every number below is taken off CONFIG_REGISTRY or off the
firings, and every title, condition and verdict is a slice of the document.

Prints the table and writes build/CONFIG_PORT_REPORT.md.

    python tools/cfg_port_report.py
"""
import collections
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))

from finastro.rules import fire                                 # noqa: E402
from finastro.rules import config_rules as C                    # noqa: E402
from finastro.rules.config_catalogue import GROUPS              # noqa: E402
from finastro.sky import Sky                                    # noqa: E402
from finastro.config import CONF                                # noqa: E402
from finastro.verdicts import build_verdicts                    # noqa: E402

sky = Sky.load()
firings = fire(C.CONFIG_REGISTRY, sky)
per_rule = collections.Counter(f.rule_id for f in firings)
per_rule_loc = collections.defaultdict(collections.Counter)
for f in firings:
    per_rule_loc[f.rule_id][f.location] += 1
by_group = C.by_group()

print(f"{'group':<18} {'#':>2}  {'status':<10} {'fires':>5} {'mum':>4} {'ny':>4}"
      "  verdict / blocked-on")
print("-" * 118)
for g in GROUPS:
    r = by_group[g.key]
    if r.status == "blocked":
        tail = "BLOCKED: " + " + ".join(r.missing_inputs)
        n = mum = ny = ""
    else:
        n = per_rule.get(r.id, 0)
        mum = per_rule_loc[r.id]["mumbai"]
        ny = per_rule_loc[r.id]["new_york"]
        tail = repr(r.verdict_text) + f"  [{r.verdict_from}]"
    st = "resolved" if r.status == "resolved_ambiguity" else r.status
    print(f"{g.block.id:<18} {g.n:>2}  {st:<10} {str(n):>5} {str(mum):>4} "
          f"{str(ny):>4}  {tail}")

print()
print(f"registered {len(C.CONFIG_REGISTRY)} | ported {len(C.ported())} | "
      f"blocked {len(C.blocked_rules())} | firings {len(firings)}")
print("blocked by input:", dict(C.missing_input_counts()))
zero = C.zero_firing(firings)
print(f"ported but never firing in 2027: {len(zero)}")
for r in zero:
    print("   ", r.id, "|", r.section.key)
print()
print("verdict provenance:",
      dict(collections.Counter(r.verdict_from for r in C.CONFIG_REGISTRY)))
print("null verdicts:",
      sum(1 for r in C.CONFIG_REGISTRY if r.verdict_text is None))


# --------------------------------------------------------------- the report
ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "build" / "CONFIG_PORT_REPORT.md"
L: list[str] = []
A = L.append

A("# The instrument configuration sections, ported")
A("")
A(f"**{len(C.ported())} of {len(GROUPS)} groups ported; "
  f"{len(C.blocked_rules())} blocked, each on a named input.** Generated by "
  "`tools/cfg_port_report.py` off `finastro/rules/config_rules.CONFIG_REGISTRY` "
  "and `build/astronomy_2027.json`. Nothing on this page is typed: the counts "
  "come from the registry, the titles and verdicts are slices of "
  "`data/source_2026.html`, the firing counts come from `fire()`, and the "
  "row counts under \"What the port is actually worth\" come from "
  "`verdicts.build_verdicts()` — the same call the calendar renders from.")
A("")
A("These are **not** catalogue-B sections. They live in their own registry, "
  "`ConfigGroup.b` is None, and `rules.sections_ported()` cannot see them, so "
  "catalogue B's 141/141 is unchanged by this port and means exactly what it "
  "meant before.")
A("")
A("## The verdict is stated in two elements, and that is the whole trap")
A("")
A("A catalogue-B verdict is sliced out of its own section. A configuration "
  "verdict is sliced out of **two**: the block's `<h2>` carries the direction "
  "and the group heading carries the condition. *Silver — Bullish "
  "Configuration* + *Venus Mars Together* is one statement in two halves.")
A("")
naive = [g for g in GROUPS if " — " not in g.title and " - " not in g.title]
A(f"**{len(naive)} of the {len(GROUPS)} group headings state no direction after "
  f"a dash of their own.** A port that sliced only the group heading — the "
  f"catalogue-B operation, applied unchanged — would have produced {len(naive)} "
  f"rules with `verdict_text = None`, and every one would have rendered as a "
  f"blank cell rather than as an error. That is the `family` half-match in a "
  f"new costume and the fifth instance of the shape.")
A("")
A("`finastro/rules/config_catalogue.check_verdict` runs at REGISTRATION, before "
  "any rule can fire, and raises `SilentVerdict` on three things: a null "
  "verdict under a directional block, a verdict that is not a substring of the "
  "document, and a verdict with no attribution. The import fails; it is not a "
  "report. The check was written before the first rule, not after.")
A("")
prov = collections.Counter(r.verdict_from for r in C.CONFIG_REGISTRY)
A(f"Result: **{prov['block_h2']} verdicts come from the block `<h2>`, "
  f"{prov['title']} from the group heading, and none is null.** "
  "`tests/test_rule_layer.py` asserts all of that, runs the naive slice as a "
  "counterfactual, and checks that the guard actually refuses each of the "
  "three cases rather than being decoration.")
A("")
A("## Per group")
A("")
for bid in sorted({g.block.id for g in GROUPS},
                  key=lambda b: [g.block.id for g in GROUPS].index(b)):
    blk = next(g.block for g in GROUPS if g.block.id == bid)
    A(f"### `{bid}` — {blk.instrument}, {blk.direction}, {blk.pages}")
    A("")
    A(f"Block heading, verbatim: **{blk.h2}**")
    A("")
    A("| # | group (as the document heads it) | status | verdict | from | 2027 firings |")
    A("| --- | --- | --- | --- | --- | --- |")
    for g in [x for x in GROUPS if x.block.id == bid]:
        r = by_group[g.key]
        if r.status == "blocked":
            st = "**blocked**"
            fires = "—"
            verd = "`" + " + ".join(r.missing_inputs) + "`"
            src = "—"
        else:
            st = "ported" if r.status == "executable" else "ported *(resolved)*"
            n = per_rule.get(r.id, 0)
            fires = (f"{n}" if n else "**0**") + (
                f" ({per_rule_loc[r.id]['mumbai']} Mum / "
                f"{per_rule_loc[r.id]['new_york']} NY)" if n else "")
            verd = f"*{r.verdict_text}*"
            src = f"`{r.verdict_from}`"
        A(f"| {g.n} | {g.title} | {st} | {verd} | {src} | {fires} |")
    A("")
A("## The blocked twenty, by input")
A("")
A("| input | groups | is it one of the survey's five? |")
A("| --- | --- | --- |")
for k, v in sorted(C.missing_input_counts().items(), key=lambda kv: -kv[1]):
    if not v:
        continue
    A(f"| `{k}` | **{v}** | "
      + ("yes" if k in C.SURVEY_INPUTS else
         "**no — and not an input the document withholds: a consequence of "
         "§12.10**") + " |")
A("")
A("`silver-bearish#9` is blocked on two inputs and appears in two rows; the "
  "group total is 20, not 21.")
A("")
for k in C.MISSING_INPUTS:
    if C.missing_input_counts()[k]:
        A(f"* **`{k}`** — {C.MISSING_INPUTS[k]}")
A("")
A("## Where the port disagreed with the scope survey")
A("")
A("The survey classed 41 groups READY. Three of them are blocked here on "
  "evidence found while writing them, and one group it had not counted was "
  "ported. Net 38.")
A("")
for key in ("gold-bullish#6", "silver-bullish#10", "silver-bearish#6",
            "silver-bullish#11"):
    r = by_group[key]
    A(f"* **`{key}`** *{r.section.title}* — "
      + ("**blocked** on `" + " + ".join(r.missing_inputs) + "`. "
         if r.status == "blocked" else "**ported**, as a resolved ambiguity. ")
      + r.notes)
A("")
A("## Ported but never firing in 2027")
A("")
A(f"{len(zero)} of the {len(C.ported())}. Surfaced rather than tolerated: a "
  "rule that never fires is either correct or a porting error and the two look "
  "identical from outside. Each is pinned by name with its reason in "
  "`tests/test_rule_layer.py::"
  "test_configuration_zero_firings_are_each_the_kind_they_claim`, so a "
  "thirteenth appearing fails the harness.")
A("")
for r in zero:
    A(f"* `{r.section.key}` — {r.section.title}")
A("")
# ---------------------------------------------------------------------------
# What the port is actually worth.
#
# The 2026 fixture cannot answer this -- it measures a general event calendar
# and these are instrument verdicts -- and no other page reported it. Computed
# here off the SAME build_verdicts() the calendar renders from, so it moves if
# the routing moves and nothing is typed twice.
# ---------------------------------------------------------------------------
_VS = build_verdicts(sky)
_CFG_IDS = {r.id for r in C.CONFIG_REGISTRY}
_INST = ["MCXGOLD", "GC", "MCXSILVER", "SI", "SUGAR"]


def _split(inst):
    """(catalogue-B rows, those of them carrying a verdict, config rows)."""
    b = [v for v in _VS if v.instrument == inst and v.rule_id not in _CFG_IDS]
    c = [v for v in _VS if v.instrument == inst and v.rule_id in _CFG_IDS]
    return b, [v for v in b if v.verdict_text], c


_ALL_CFG = [v for v in _VS if v.rule_id in _CFG_IDS]
_ALL_B = [v for v in _VS if v.rule_id not in _CFG_IDS]
_SIG_CFG = collections.Counter(v.significance for v in _ALL_CFG)
_SIG_B5 = collections.Counter(
    v.significance for v in _ALL_B if v.instrument in _INST)
_MW = _SIG_B5.get("market_wide", 0)
_CO = _SIG_B5.get("condition_only", 0)
_IS = _SIG_CFG.get("instrument_specific", 0)
# What catalogue B alone contributes to that column -- i.e. what the figure was
# before the wiring. Read, not asserted: `significance_of` reaches
# `instrument_specific` only on its `is_config_rule` branch.
_IS_FROM_B = _SIG_B5.get("instrument_specific", 0)
_PCT = 100 * _IS / (_IS + _MW)

A("## What the port is actually worth")
A("")
A("Neither the 2026 fixture nor any other page reported this, so it is "
  "computed here. **The fixture's two-window diff is not this number**, and "
  "the last subsection exists so nobody later reads it as one.")
A("")
A(f"A rebuild emits **{len(_VS):,} verdict rows**: **{len(_ALL_B):,} "
  f"catalogue B** and **{len(_ALL_CFG):,} configuration**, all from the same "
  "`build_verdicts()` the calendar renders from.")
A("")
A("### The configuration rows, by instrument")
A("")
A("| instrument | catalogue-B rows | of those, carrying a verdict | "
  "configuration rows | own-block share of verdict-bearing rows |")
A("| --- | ---: | ---: | ---: | ---: |")
for _i in _INST:
    _b, _bv, _c = _split(_i)
    _den = len(_c) + len(_bv)
    A(f"| `{_i}` | {len(_b)} | {len(_bv)} | **{len(_c)}** | "
      + (f"**{100 * len(_c) / _den:.0f}%**" if _den else "—") + " |")
_B5 = sum(len(_split(i)[0]) for i in _INST)
_BV5 = sum(len(_split(i)[1]) for i in _INST)
_C5 = sum(len(_split(i)[2]) for i in _INST)
A(f"| **all five** | **{_B5:,}** | **{_BV5}** | **{_C5:,}** | "
  f"**{100 * _C5 / (_C5 + _BV5):.0f}%** |")
A("")
A("No other instrument carries a configuration row: the eleven-instrument set "
  "also holds NIFTY, BANKNIFTY, SPX, NDX, CL and USDINR, and every one of "
  "them is at zero, because the source prints configuration blocks for these "
  "three commodities and no others.")
A("")
A(f"**All {len(_ALL_CFG):,} configuration rows carry a verdict; "
  f"{sum(1 for v in _ALL_CFG if not v.verdict_text)} is null.** That is an "
  "invariant rather than a count. `config_catalogue.check_verdict` refuses a "
  "null verdict at REGISTRATION, so a configuration rule cannot exist without "
  "one; the only path by which a null configuration row could ever appear was "
  "tier_4's USDINR emit-anyway, now scoped to catalogue B. A null "
  "configuration row appearing means the routing has re-widened.")
A("")
A("### The number that matters: whose statement the row is")
A("")
A("A row on `MCXGOLD` gets there two ways, and `significance` already "
  "separates them:")
A("")
A("* **`market_wide`** — a catalogue-B rule printed a general verdict, and "
  "the row reaches gold because the rule's BODIES resolve to gold through the "
  "reconciled rulership table. The document never named gold. That resolution "
  "is an inference *this layer makes*.")
A("* **`instrument_specific`** — the source printed the verdict under "
  "*Gold — Bullish Configuration*. The block names the instrument, "
  "`config_instruments_for` reads that name, and no table is consulted. "
  "Nothing is inferred.")
A("")
A("Across gold, silver and sugar:")
A("")
A("| significance | rows | whose statement it is |")
A("| --- | ---: | --- |")
A(f"| `instrument_specific` | **{_IS:,}** | the source's, about this "
  "instrument |")
A(f"| `market_wide` | {_MW} | the source's, about the market — routed here "
  "by us |")
A(f"| `condition_only` | {_CO} | nobody's: a condition with no printed "
  "direction |")
A("")
A(f"**Before the wiring that first row read {_IS_FROM_B}.** Not low — zero, "
  "and still zero from catalogue B today, because `significance_of` reaches "
  "`instrument_specific` only on its `is_config_rule` branch. Every "
  f"directional row gold, silver and sugar carried was one of the {_MW} "
  "`market_wide` rows: a verdict the source wrote about the market, delivered "
  "to a named contract by our rulership table.")
A("")
A(f"**{_IS:,} of the {_IS + _MW:,} verdict-bearing rows on these three "
  f"instruments — {_PCT:.0f}% — are now statements the document makes about "
  "the instrument itself.** That is the port's value, in the one unit that "
  "distinguishes the two cases.")
A("")
A("It is **not** a claim that those verdicts are right. `confidence` is "
  "`untested` on every row, no code path raises it, and "
  "`label_scheme_signoff` is still open. It is a claim about PROVENANCE, "
  "which is the axis this layer exists to keep honest.")
A("")
_SUGAR_ROWS = sum(1 for v in _ALL_CFG if v.instrument == "SUGAR")
_SUGAR_CFG_RULES = len({v.rule_id for v in _ALL_CFG if v.instrument == "SUGAR"})
_SUGAR_B_RULES = len({v.rule_id for v in _ALL_B if v.instrument == "SUGAR"})
A(f"**SUGAR is the sharpest single case.** {_SUGAR_B_RULES} catalogue-B rules "
  "reach it, every one through Venus and the `sugar_and_soft_goods` "
  f"rulership. Of its own nine configuration groups, {_SUGAR_CFG_RULES} fires "
  f"in {CONF['year']} — and that one group produces {_SUGAR_ROWS} rows. The "
  "document devotes pp.168-175 to sugar and the calendar quoted none of it; "
  "it now quotes one group of it. A small number, and a different kind of "
  "number.")
A("")
A("### Why the two-window fixture diff is not this number")
A("")
A("`build/MONTHLY_2026_FIXTURE.md` measures the layer against the source's "
  "**monthly calendar**, and the wiring moved it by **two windows of 354** "
  "(166 → 168) and two event names of 147. That figure is correct and is "
  "reported honestly there. **It is not a measure of this port.**")
A("")
A("The two artefacts are about different things:")
A("")
A("* The monthly calendar is a **general event calendar** — dated rows for "
  "the market at large, its 147 event names panchang, transit and aspect "
  "events.")
A("* The configuration sections are **instrument verdicts** for gold, silver "
  "and sugar. The document keeps them in separate chapters because they say a "
  "different kind of thing.")
A("")
A("They intersect in two event names, so the port could move the fixture by "
  "about two rows and did. **A near-zero fixture diff is the EXPECTED result "
  "of a correct port, not evidence of a small one.** Measuring a gold verdict "
  "against a general calendar is measuring the wrong denominator — and a "
  "LARGE diff would have meant configuration verdicts were leaking into "
  "general rows, which is the failure `config_instruments_for` exists to "
  "prevent. The fixture is the right instrument for catalogue B's coverage "
  "and the wrong instrument for this.")
A("")
A("Both numbers are true; neither substitutes for the other:")
A("")
A("> **2 of 354 windows** is what the port did to the **general event "
  "calendar** — nearly all it could do.")
A(f"> **{_IS:,} rows, {_PCT:.0f}% of the verdict-bearing rows on gold, silver "
  "and sugar**, is what it did to **those three instruments' own verdicts** "
  "— which is what it was for.")
A("")
A("Quoting the first alone understates the port by the whole of its subject. "
  "Quoting the second alone hides that the general calendar barely moved. "
  "This build has twice shipped a figure that was right and a page that was "
  "not (`141/141`, then `0 of 58`); stating either of these without the other "
  "would be the third.")
A("")
A("## What this port does NOT do")
A("")
A("* It does not make a configuration row TRUE. `verdicts.py` now fires "
  "both registries and the rows above do reach the calendar, but a "
  "ported group is a reproduction of the document's condition, not "
  "evidence for it.")
A("* It does not raise a confidence or emit a verdict record. "
  "`label_scheme_signoff` is still open.")
A("* It does not settle any of the six missing inputs.")
A("")
A("Financial astrology is a speculative interpretive framework. Nothing on "
  "this page is a forecast or investment advice.")

OUT.write_text(chr(10).join(L) + chr(10), encoding="utf-8")
print()
print(f"wrote {OUT.relative_to(ROOT)}  ({len(L)} lines)")
